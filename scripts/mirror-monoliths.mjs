#!/usr/bin/env node
// mirror-monoliths: pull the canonical monolith sources (the BOOK, the arc-170
// realizations) from their source-of-truth files in the sibling substrate repos
// and serve them in two interfaces the reader chooses between:
//
//   1. RAW WHOLE — public/blog/<name>.md: the continuous scroll, and an agent's
//      one fetch. Too large to render as a single HTML page (a 38k-line render
//      OOMs the build), so it serves as static markdown. The thin .mdx landing
//      at /blog/<name>/ links to it.
//
//   2. RENDERED CHUNKS — one CONTENT PAGE per top-level `##` segment, written to
//      src/content/docs/blog/<name>/<NN>-<slug>.md. Each chapter / entry renders
//      as a normal (nice) Starlight post, lands in the autogenerated sidebar, AND
//      inherits a `.md` companion for free: copy-markdown mirrors it to dist, and
//      the middleware serves it on `Accept: text/markdown`. We don't build
//      dual-reading — content pages already have it.
//
// The author deliberately varies heading shapes so segment boundaries are
// unmistakable; we split on exactly those markers.
//
// LOCAL maintenance tool — NOT part of the Cloudflare build (that runner checks
// out only this repo; it has no sibling repos). Run by hand after the substrate's
// monoliths grow, then commit the result:
//   node scripts/mirror-monoliths.mjs        (or: npm run mirror)
// One direction only: source-of-truth → serve. (Live-fetch-at-build was rejected
// on purpose — it would couple every deploy to the network to solve a problem
// that only exists at push.)
//
// `--check` (wired into postbuild): a freshness probe, never a write. Sources
// ABSENT (CF/CI) → silent skip, exit 0; PRESENT + served whole matches → fresh;
// behind → loud "run `npm run mirror`" (exit 0 always — a reminder, not a blocker).

import { readFile, writeFile, mkdir, rm, readdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join } from "node:path";

// Each monolith: its canonical source (relative to this repo root, reaching into
// a sibling repo), the raw-whole serve path, the content-collection directory the
// per-segment chunk pages are generated into, and the regex matching a top-level
// segment heading.
const MONOLITHS = [
  {
    name: "The BOOK (trunk)",
    src: "../holon-lab-trading/BOOK.md",
    whole: "public/blog/book.md",
    chunks: "src/content/docs/blog/book",
    segment: /^## (?:Chapter|Intermission) /,
  },
  {
    name: "Arc 170 — Full Realizations",
    src: "../wat-rs/docs/arc/2026/05/170-program-entry-points/INTERSTITIAL-REALIZATIONS.md",
    whole: "public/blog/arc-170-realizations.md",
    chunks: "src/content/docs/blog/arc-170-realizations",
    // No trailing space: a few entries carry a suffixed date (e.g. `2026-05-21b`)
    // or an immediate parenthetical; match the date prefix, not a space after it.
    segment: /^## 2026-\d\d-\d\d/,
  },
];

// A heading line → a stable, filesystem- and URL-safe slug.
function slugify(heading) {
  return heading
    .replace(/^#+\s*/, "")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1") // unwrap [text](url) -> text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 70)
    .replace(/-+$/g, "");
}

// A heading line → a clean page/sidebar title: marker stripped, any markdown link
// unwrapped, trailing caps-slash facet run dropped (keep the first two " — "
// fields), and length-capped so song entries don't dump 80 chars into the sidebar.
function chunkTitle(heading) {
  const bare = heading
    .replace(/^#+\s*/, "")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .trim();
  const beforeFacets = bare.split(" — ").slice(0, 2).join(" — ");
  return beforeFacets.length > 90 ? beforeFacets.slice(0, 88) + "…" : beforeFacets;
}

const CHECK = process.argv.includes("--check");

let problems = 0;
let written = 0;
let drift = 0;
let absent = 0;

for (const m of MONOLITHS) {
  if (!existsSync(m.src)) {
    if (CHECK) {
      absent++;
      continue;
    }
    console.error(`  ✗ ${m.name}: canonical source missing: ${m.src} (is the sibling repo checked out at the expected path?)`);
    problems++;
    continue;
  }

  const text = await readFile(m.src, "utf-8");
  const lines = text.split("\n");

  // Find every top-level segment boundary by line index.
  const bounds = [];
  lines.forEach((line, i) => {
    if (m.segment.test(line)) bounds.push(i);
  });
  if (bounds.length === 0) {
    if (CHECK) continue;
    console.error(`  ✗ ${m.name}: zero segments matched ${m.segment} — the division markers drifted; refusing to mirror a structureless blob`);
    problems++;
    continue;
  }

  // --check: compare the served whole to source; never write.
  if (CHECK) {
    const served = existsSync(m.whole) ? await readFile(m.whole, "utf-8") : "";
    if (served !== text) {
      const d = lines.length - (served ? served.split("\n").length : 0);
      console.error(`  ⚠ ${m.name}: served copy is STALE vs source (${d >= 0 ? "+" : ""}${d} lines) — run \`npm run mirror\` before pushing`);
      drift++;
    }
    continue;
  }

  // --- interface 1: raw whole ------------------------------------------------
  const prevWhole = existsSync(m.whole) ? await readFile(m.whole, "utf-8") : "";
  if (prevWhole !== text) {
    await mkdir(dirname(m.whole), { recursive: true });
    await writeFile(m.whole, text);
    written++;
  }
  const delta = prevWhole ? lines.length - prevWhole.split("\n").length : lines.length;

  // --- interface 2: rendered chunk content pages -----------------------------
  // Rebuild the chunk directory from scratch each run so a removed or renamed
  // upstream segment can't leave a stale page behind (the mirror owns this dir;
  // nothing else writes here).
  if (existsSync(m.chunks)) await rm(m.chunks, { recursive: true, force: true });
  await mkdir(m.chunks, { recursive: true });

  const seenSlugs = new Set();
  for (let c = 0; c < bounds.length; c++) {
    const start = bounds[c];
    const end = c + 1 < bounds.length ? bounds[c + 1] : lines.length;
    const heading = lines[start];
    const num = String(c + 1).padStart(3, "0");
    let slug = slugify(heading);
    if (!slug || seenSlugs.has(slug)) slug = `${slug || "segment"}-${num}`;
    seenSlugs.add(slug);

    // The page title is the segment heading; the body is everything AFTER it (the
    // frontmatter title becomes the rendered H1, so the `## heading` line is
    // dropped to avoid a duplicate). Starlight renders the rest; copy-markdown
    // gives it a `.md` companion; the sidebar autogenerates from this directory.
    const title = chunkTitle(heading);
    const body = lines.slice(start + 1, end).join("\n").replace(/^\n+/, "").replace(/\s+$/, "") + "\n";
    const frontmatter = `---\ntitle: ${JSON.stringify(title)}\nsidebar:\n  order: ${c + 1}\n---\n\n`;
    await writeFile(join(m.chunks, `${num}-${slug}.md`), frontmatter + body);
    written++;
  }

  const newest = chunkTitle(lines[bounds[bounds.length - 1]]);
  console.error(
    `  ✓ ${m.name}: ${bounds.length} chunk pages, whole ${lines.length} lines (${delta >= 0 ? "+" : ""}${delta}) — newest: ${newest}`
  );
}

if (CHECK) {
  if (absent) {
    // Cloudflare / CI: no sibling repos to compare against. Not our job here.
    process.exit(0);
  }
  if (drift) {
    console.error(`\n[mirror-monoliths] ⚠ ${drift} monolith(s) drifted from source — run \`npm run mirror\`, then commit the refresh.`);
  } else {
    console.error(`[mirror-monoliths] ✓ served monoliths are fresh vs source.`);
  }
  process.exit(0);
}

if (problems) {
  console.error(`\n[mirror-monoliths] ✗ ${problems} problem(s) — fix before serving.`);
  process.exit(1);
}
console.error(`\n[mirror-monoliths] ✓ mirrored, divisions validated (${written} file${written === 1 ? "" : "s"} written this run).`);
