#!/usr/bin/env node
// mirror-monoliths: pull the canonical monolith sources (the BOOK, the arc-170
// realizations) from their source-of-truth files in the sibling substrate repos
// and copy them into public/blog/ in two interfaces the reader chooses between:
//   1. RAW WHOLE — public/blog/<name>.md (the continuous scroll; one fetch for an agent)
//   2. CHUNKED   — public/blog/<name>/<NN>-<slug>.md, one file per top-level
//      `##` segment (the author varies heading shapes so segment boundaries are
//      unmistakable — we split on exactly those markers), plus a regenerated
//      chunk index injected into the landing page between sentinels.
//
// These are intentional continuous monoliths (a 37k-line single HTML render is
// brutal on browsers and OOMs the build), so neither interface is a rendered
// page — both are markdown. The thin .mdx landing renders; it links to both.
//
// LOCAL maintenance tool — NOT part of the Cloudflare build (that env has no
// sibling repos). Run by hand after the substrate's monoliths grow:
//   node scripts/mirror-monoliths.mjs        (or: npm run mirror)
// The refreshed public/blog/** is committed and served statically. One direction
// only: source-of-truth → serve. Curated artifacts (the hand-written cliffnotes
// distillation) are marked `protected` and are never overwritten — they are NOT
// mirrors.

import { readFile, writeFile, mkdir, rm } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join } from "node:path";

// Each monolith: its canonical source (relative to this repo root, reaching into
// a sibling repo), the raw-whole serve path, the chunk directory, the landing
// page whose index region we regenerate, and the regex that matches a top-level
// segment heading. `protected` entries are reported and skipped, never written.
const MONOLITHS = [
  {
    name: "The BOOK (trunk)",
    src: "../holon-lab-trading/BOOK.md",
    whole: "public/blog/book.md",
    chunkDir: "public/blog/book",
    landing: "src/content/docs/blog/book.mdx",
    segment: /^## (?:Chapter|Intermission) /,
  },
  {
    name: "Arc 170 — Full Realizations",
    src: "../wat-rs/docs/arc/2026/05/170-program-entry-points/INTERSTITIAL-REALIZATIONS.md",
    whole: "public/blog/arc-170-realizations.md",
    chunkDir: "public/blog/arc-170-realizations",
    landing: "src/content/docs/blog/arc-170-realizations.mdx",
    // No trailing space: a few entries carry a suffixed date (e.g. `2026-05-21b`)
    // or an immediate parenthetical; match the date prefix, not a space after it.
    segment: /^## 2026-\d\d-\d\d/,
  },
  {
    name: "Arc 170 — Cliff Notes",
    protected: true,
    note: "src/content/docs/blog/arc-170-cliffnotes.md is a hand-written public distillation, not a mirror of the canonical bootstrap index — refresh by hand.",
  },
];

// MDX comment syntax ({/* */}, not <!-- -->) — the landings are .mdx (so the
// copy-markdown postbuild step skips them and can't clobber the raw serve), and
// MDX parses <!-- as JSX and chokes.
const BEGIN = "{/* BEGIN CHUNK INDEX — regenerated by scripts/mirror-monoliths.mjs; do not edit by hand */}";
const END = "{/* END CHUNK INDEX */}";

// A heading line → a stable, filesystem- and URL-safe slug. Strips the leading
// `## `, any markdown link wrapper, lowercases, and keeps word characters.
function slugify(heading) {
  return heading
    .replace(/^#+\s*/, "")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1") // unwrap [text](url) -> text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 70)
    .replace(/-+$/g, "");
}

// The display text for an index entry: the heading with the `## ` and any
// trailing caps-slash facet run trimmed, so song entries don't dump 80 chars.
function indexLabel(heading) {
  // Strip the marker, unwrap any markdown link in the heading (a nested link
  // would break the index entry's own link), drop any trailing caps-slash facet
  // run (keep the first two " — " fields), and remove characters that are unsafe
  // to inject into a .mdx file as plain link text (`<`/`{` parse as JSX;
  // backticks can be left unbalanced by truncation).
  const bare = heading
    .replace(/^#+\s*/, "")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/[`<>{}]/g, "");
  const beforeFacets = bare.split(" — ").slice(0, 2).join(" — ");
  return beforeFacets.length > 90 ? beforeFacets.slice(0, 88) + "…" : beforeFacets;
}

let problems = 0;
let touched = 0;

for (const m of MONOLITHS) {
  if (m.protected) {
    console.error(`  ~ ${m.name}: PROTECTED — ${m.note}`);
    continue;
  }
  if (!existsSync(m.src)) {
    console.error(`  ✗ ${m.name}: canonical source missing: ${m.src} (is the sibling repo checked out at the expected path?)`);
    problems++;
    continue;
  }
  if (!existsSync(m.landing)) {
    console.error(`  ✗ ${m.name}: landing page missing: ${m.landing} (its hand-written context isn't templatable — author it once; src/content/docs/blog/book.mdx is the model)`);
    problems++;
    continue;
  }

  const text = await readFile(m.src, "utf-8");
  const lines = text.split("\n");

  // Find every top-level segment boundary by line index.
  const bounds = [];
  lines.forEach((line, i) => {
    if (m.segment.test(line)) bounds.push(i);
  });
  if (bounds.length === 0) {
    console.error(`  ✗ ${m.name}: zero segments matched ${m.segment} — the division markers drifted; refusing to mirror a structureless blob`);
    problems++;
    continue;
  }

  // --- interface 1: raw whole ------------------------------------------------
  const prevWhole = existsSync(m.whole) ? await readFile(m.whole, "utf-8") : "";
  if (prevWhole !== text) {
    await mkdir(dirname(m.whole), { recursive: true });
    await writeFile(m.whole, text);
    touched++;
  }
  const delta = prevWhole ? lines.length - prevWhole.split("\n").length : lines.length;

  // --- interface 2: chunks (one file per segment) ----------------------------
  // Rebuild the chunk dir from scratch each run so a removed/renamed upstream
  // segment can't leave a stale chunk behind (the mirror is the source of truth
  // for the dir; nothing else writes there).
  if (existsSync(m.chunkDir)) await rm(m.chunkDir, { recursive: true, force: true });
  await mkdir(m.chunkDir, { recursive: true });

  const index = [];
  const seenSlugs = new Set();
  for (let c = 0; c < bounds.length; c++) {
    const start = bounds[c];
    const end = c + 1 < bounds.length ? bounds[c + 1] : lines.length;
    const heading = lines[start];
    const body = lines.slice(start, end).join("\n").replace(/\s+$/, "") + "\n";
    const num = String(c + 1).padStart(3, "0");
    let slug = slugify(heading);
    if (!slug || seenSlugs.has(slug)) slug = `${slug || "segment"}-${num}`;
    seenSlugs.add(slug);
    const file = `${num}-${slug}.md`;
    await writeFile(join(m.chunkDir, file), body);
    const url = `/blog/${m.chunkDir.replace(/^public\/blog\//, "")}/${file}`;
    index.push(`- [${indexLabel(heading)}](${url})`);
  }

  // --- regenerate the chunk index in the landing, between sentinels ----------
  const landingText = await readFile(m.landing, "utf-8");
  const b = landingText.indexOf(BEGIN);
  const e = landingText.indexOf(END);
  if (b === -1 || e === -1) {
    console.error(`  ✗ ${m.name}: landing ${m.landing} is missing the chunk-index sentinels — add a region:\n      ${BEGIN}\n      ${END}`);
    problems++;
    continue;
  }
  const before = landingText.slice(0, b + BEGIN.length);
  const after = landingText.slice(e);
  const updatedLanding = `${before}\n\n${index.join("\n")}\n\n${after}`;
  if (updatedLanding !== landingText) {
    await writeFile(m.landing, updatedLanding);
    touched++;
  }

  const newest = indexLabel(lines[bounds[bounds.length - 1]]);
  console.error(
    `  ✓ ${m.name}: ${bounds.length} chunks, ${lines.length} lines (${delta >= 0 ? "+" : ""}${delta}) — newest: ${newest}`
  );
}

if (problems) {
  console.error(`\n[mirror-monoliths] ✗ ${problems} problem(s) — fix before serving.`);
  process.exit(1);
}
console.error(`\n[mirror-monoliths] ✓ mirrored, divisions validated (${touched} file${touched === 1 ? "" : "s"} written this run).`);
