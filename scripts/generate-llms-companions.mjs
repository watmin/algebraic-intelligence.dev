// Regenerate the markdown-companion URL listings in public/llms.txt by walking
// src/content/docs/blog/. Replaces the content between sentinel markers.
//
// Lives in postbuild so every `npm run build` keeps llms.txt in sync with the
// blog directory: add a new story post, run build, llms.txt picks it up.
//
// Why sentinels: the rest of llms.txt is hand-curated (descriptions carry
// editorial judgment, voice, framing). Only the URL listings are mechanical.
// Sentinels let us regenerate the mechanical part without touching the prose.
//
// The sentinels live inside HTML comments so they're valid markdown and don't
// render in any reader that respects markdown's HTML-comment passthrough.

import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";
import { existsSync } from "node:fs";

const SRC = "src/content/docs/blog";
const LLMS = "public/llms.txt";
const SITE = "https://algebraic-intelligence.dev";

const BEGIN = "<!-- BEGIN AUTO-GENERATED MD COMPANIONS — regenerated by scripts/generate-llms-companions.mjs; do not edit by hand -->";
const END = "<!-- END AUTO-GENERATED MD COMPANIONS -->";

// Top-level pages get a short hand-curated label so the listing reads cleanly.
// Anything not in this map falls through to "no label" (URL alone).
const TOP_LEVEL_LABELS = {
  "topology.md": "The Topology",
  "book.md": "The Book (trunk; ~36k lines)",
  "arc-170-cliffnotes.md": "Arc 170 Cliff Notes (load first)",
  "arc-170-realizations.md": "Arc 170 Full Realizations",
  "guide.md": "The Guide",
  "circuit.md": "The Circuits",
};

if (!existsSync(SRC)) {
  console.error(`generate-llms-companions: source missing: ${SRC}`);
  process.exit(1);
}
if (!existsSync(LLMS)) {
  console.error(`generate-llms-companions: target missing: ${LLMS}`);
  process.exit(1);
}

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...(await walk(full)));
    } else if (entry.isFile() && entry.name.endsWith(".md")) {
      out.push(full);
    }
  }
  return out;
}

const files = (await walk(SRC)).map((f) => relative(SRC, f)).sort();

const topLevel = files.filter((f) => !f.includes("/"));
const story = files.filter((f) => f.startsWith("story/")).map((f) => f.slice("story/".length));
const primers = files.filter((f) => f.startsWith("primers/")).map((f) => f.slice("primers/".length));

function formatEntry(url, label) {
  return label ? `- [${url}](${url}) — ${label}` : `- [${url}](${url})`;
}

const sections = [];

sections.push("### Trunk and branches");
sections.push("");
// The Book's full text lives at public/blog/book.md (static, not in the
// content collection — its 36k-line HTML render was OOMing the build), so the
// src walker above doesn't see it. Add it explicitly at the top of the trunk.
sections.push(formatEntry(`${SITE}/blog/book.md`, "The Book (trunk; ~36k lines)"));
for (const f of topLevel) {
  if (f === "book.md") continue; // handled above; would otherwise duplicate
  const url = `${SITE}/blog/${f}`;
  sections.push(formatEntry(url, TOP_LEVEL_LABELS[f] || ""));
}

sections.push("");
sections.push("### Primers");
sections.push("");
for (const f of primers) {
  const url = `${SITE}/blog/primers/${f}`;
  sections.push(formatEntry(url, ""));
}

sections.push("");
sections.push("### Story posts");
sections.push("");
for (const f of story) {
  const url = `${SITE}/blog/story/${f}`;
  sections.push(formatEntry(url, ""));
}

const generated = sections.join("\n");

const current = await readFile(LLMS, "utf8");

const beginIdx = current.indexOf(BEGIN);
const endIdx = current.indexOf(END);

if (beginIdx === -1 || endIdx === -1) {
  console.error(`generate-llms-companions: sentinels not found in ${LLMS}.`);
  console.error(`Expected to find:\n  ${BEGIN}\n  ${END}`);
  console.error(`Add them around the auto-generated section, then re-run.`);
  process.exit(1);
}
if (endIdx < beginIdx) {
  console.error(`generate-llms-companions: END sentinel appears before BEGIN. Fix llms.txt sentinel order.`);
  process.exit(1);
}

const before = current.slice(0, beginIdx + BEGIN.length);
const after = current.slice(endIdx);
const updated = `${before}\n\n${generated}\n\n${after}`;

if (updated === current) {
  console.log(`generate-llms-companions: no change (${files.length} companions already in sync).`);
  process.exit(0);
}

await writeFile(LLMS, updated);
console.log(`generate-llms-companions: regenerated ${files.length} companion URLs in ${LLMS}`);
console.log(`  trunk + branches: ${topLevel.length}, primers: ${primers.length}, story posts: ${story.length}`);
